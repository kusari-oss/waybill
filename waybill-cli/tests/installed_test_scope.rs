//! Spec 1533 (#1564): an installed tree's test payload is reported with the
//! test scope. Synthetic prefixes in a tempdir; nothing is fetched.

#![allow(clippy::unwrap_used)]

mod common;

use std::path::Path;

use common::installed_lib::{
    component, components, doc_field_all_formats, dpkg_owning, elf_shared_lib, prop, row_all_formats, scan, scan_with,
    write, Docs,
};
use serde_json::Value;

const C226: &str = "waybill:test-scope-coverage";

fn put(root: &Path, rel: &str, bytes: &[u8]) {
    let p = root.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, bytes).unwrap();
}

/// An executable script: a file-tier shape (spec 133) the orphan walker
/// emits. Data files and `.py` sources get no component, so this feature
/// has nothing to scope for them (FR-008).
fn script(root: &Path, rel: &str) {
    write(root, rel, &format!("#!/bin/sh\n# {rel}\n"));
}

/// A distinct ELF per file, so no two share a content hash.
fn elf(root: &Path, rel: &str) {
    put(root, rel, &elf_shared_lib(format!("\0{rel}\0").as_bytes()));
}

fn main_file(depth: usize) -> String {
    let mut s = String::from("get_filename_component(_IMPORT_PREFIX \"${CMAKE_CURRENT_LIST_FILE}\" PATH)\n");
    for _ in 0..depth {
        s.push_str("get_filename_component(_IMPORT_PREFIX \"${_IMPORT_PREFIX}\" PATH)\n");
    }
    s
}

/// The component whose name is `name` (binary and file-tier components carry
/// no stable PURL to look up).
fn named<'a>(cdx: &'a Value, name: &str) -> &'a Value {
    let found: Vec<&Value> = components(cdx).into_iter().filter(|c| c["name"] == name).collect();
    assert_eq!(found.len(), 1, "exactly one component named {name}");
    found[0]
}

/// The test scope as CycloneDX carries it, and the C62 reason; `None` when
/// unscoped.
fn scope_of(c: &Value) -> Option<String> {
    if c["scope"] != "excluded" {
        assert!(prop(c, "waybill:lifecycle-scope").is_none(), "{}: C42 without scope", c["name"]);
        return None;
    }
    assert_eq!(prop(c, "waybill:lifecycle-scope"), Some("test"), "{}", c["name"]);
    prop(c, "waybill:lifecycle-scope-derivation").map(str::to_string)
}

/// SPDX 3's purposes for the element named `name`.
fn spdx3_purposes(doc: &Value, name: &str) -> (Option<String>, Option<Value>) {
    let el = doc["@graph"].as_array().unwrap().iter().find(|e| e["name"] == name).unwrap_or_else(|| panic!("{name}"));
    (el["software_primaryPurpose"].as_str().map(str::to_string), el.get("software_additionalPurpose").cloned())
}

/// The US1 prefix: an installed library (so the directory is recognised), a
/// CTest file, a test package's exported targets, and product files.
fn us1_tree(root: &Path, declarations: bool) {
    let sdk = "opt/sdk";
    write(root, &format!("{sdk}/lib/pkgconfig/waybill-fixture-p.pc"), "Version: 1.0\n");
    elf(root, &format!("{sdk}/lib/libwaybill-fixture-p.so.1"));
    elf(root, &format!("{sdk}/bin/waybill-fixture-p-tool"));
    elf(root, &format!("{sdk}/bin/waybill-fixture-p-test"));
    script(root, &format!("{sdk}/bin/waybill-fixture-p/tests/run_x"));
    // A test package with a version, whose export set names a test binary.
    write(root, &format!("{sdk}/lib/cmake/waybill-fixture-p-tests/waybill-fixture-p-tests-config-version.cmake"), "set(PACKAGE_VERSION \"1.0\")\n");
    elf(root, &format!("{sdk}/share/waybill-fixture-p/tests/bin/unit-t"));
    script(root, &format!("{sdk}/share/waybill-fixture-p/tests/run-input"));
    script(root, &format!("{sdk}/share/waybill-fixture-p/testing-utils/helper"));
    // US3: undeclared names that look like tests or benchmarks.
    for n in ["test_waybill_fixture_op", "benchmark_waybill_fixture_op", "waybill-fixture-r-bench", "waybill-fixture-attest"] {
        elf(root, &format!("{sdk}/bin/{n}"));
    }
    if declarations {
        write(
            root,
            &format!("{sdk}/bin/waybill-fixture-p/CTestTestfile.cmake"),
            "# generated by waybill-fixture-p for install time\n\
             add_test(quick \"../waybill-fixture-p-test\" --gtest_filter=*quick*)\n\
             add_test([=[py t]=] \"python3\" \"-m\" \"pytest\" \"tests/run_x\")\n\
             add_test(var \"${WAYBILL_FIXTURE_EXE}\")\n\
             add_test(gone \"../waybill-fixture-p-missing\")\n\
             add_test(out \"../../../../../escape\")\n\
             include(script/discover_include.cmake)\n",
        );
        let dir = format!("{sdk}/lib/cmake/waybill-fixture-p-tests");
        write(root, &format!("{dir}/waybill-fixture-p-tests-targets.cmake"), &main_file(3));
        write(
            root,
            &format!("{dir}/waybill-fixture-p-tests-targets-release.cmake"),
            "set_target_properties(wf::unit PROPERTIES\n  IMPORTED_LOCATION_RELEASE \"${_IMPORT_PREFIX}/share/waybill-fixture-p/tests/bin/unit-t\"\n  )\n",
        );
    }
}

/// US1 scenarios 1-4, US2 scenario 3, US3, and C226 in all three formats.
#[test]
fn us1_declared_test_payload_is_test_scoped() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("sdk");
    us1_tree(&root, true);
    let docs = scan(&root);

    assert_eq!(scope_of(named(&docs.cdx, "waybill-fixture-p-test")).as_deref(), Some("ctest-declaration"));
    assert_eq!(scope_of(named(&docs.cdx, "run_x")).as_deref(), Some("ctest-declaration"));
    // Named by the export set and under `tests/`: the declaration wins.
    assert_eq!(scope_of(named(&docs.cdx, "unit-t")).as_deref(), Some("exported-targets-test-package"));
    // The test package's own component.
    let pkg = component(&docs.cdx, "pkg:generic/waybill-fixture-p-tests@1.0").expect("test package component");
    assert_eq!(scope_of(pkg).as_deref(), Some("exported-targets-test-package"));
    // US2 in the same tree.
    assert_eq!(scope_of(named(&docs.cdx, "run-input")).as_deref(), Some("test-directory"));
    // Product files, a near-miss directory, and US3's undeclared names.
    for n in [
        "libwaybill-fixture-p.so.1",
        "waybill-fixture-p-tool",
        "helper",
        "test_waybill_fixture_op",
        "benchmark_waybill_fixture_op",
        "waybill-fixture-r-bench",
        "waybill-fixture-attest",
    ] {
        assert_eq!(scope_of(named(&docs.cdx, n)), None, "{n} must stay unscoped");
    }
    assert_eq!(scope_of(component(&docs.cdx, "pkg:generic/waybill-fixture-p@1.0").unwrap()), None);
    // The document subject is never scoped.
    assert!(docs.cdx["metadata"]["component"].get("scope").is_none());

    // SPDX 3: `test` first, the binary role kept (FR-002, research R8).
    assert_eq!(spdx3_purposes(&docs.spdx3, "waybill-fixture-p-test"), (Some("test".into()), Some(serde_json::json!(["library"]))));
    assert_eq!(spdx3_purposes(&docs.spdx3, "waybill-fixture-p-tool").0.as_deref(), Some("library"));

    // C42, C62 and A13 agree across the three formats.
    let c42 = row_all_formats(&docs, "C42");
    assert!(c42.iter().any(|v| v.contains("test")), "{c42:?}");
    let c62 = row_all_formats(&docs, "C62");
    assert!(c62.iter().any(|v| v.contains("ctest-declaration")), "{c62:?}");
    row_all_formats(&docs, "A13");

    let cov = doc_field_all_formats(&docs, C226).expect("C226 present");
    assert_eq!(
        cov,
        serde_json::json!({
            "declarations": {"ctest": 1, "exported-targets": 2, "owned-by-os-package": 0},
            "installed-tree": "recognised",
            "locations": {"not-shipped": 1, "outside-root": 1, "resolved": 3, "unresolved": 2},
            "scoped": {"ctest-declaration": 2, "exported-targets-test-package": 2, "test-directory": 1}
        })
    );
}

/// The control: the same tree with its declarations removed scopes only
/// what the path convention covers.
#[test]
fn us1_control_without_declarations() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("sdk");
    us1_tree(&root, false);
    let docs = scan(&root);
    assert_eq!(scope_of(named(&docs.cdx, "waybill-fixture-p-test")), None);
    // Still under `tests/` in a recognised tree: the convention, not a
    // declaration, is now the recorded reason.
    for n in ["run_x", "unit-t"] {
        assert_eq!(scope_of(named(&docs.cdx, n)).as_deref(), Some("test-directory"), "{n}");
    }
    assert_eq!(scope_of(component(&docs.cdx, "pkg:generic/waybill-fixture-p-tests@1.0").unwrap()), None);
    assert_eq!(doc_field_all_formats(&docs, C226).unwrap()["declarations"]["ctest"], 0);
}

/// FR-015: a source tree with `tests/` and no installed library or OS
/// database is not an installed tree; only a declaration would scope.
#[test]
fn an_unrecognised_source_tree_is_unchanged() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("src");
    script(&root, "tests/run-fixture");
    script(&root, "src/test_plugins/run-p");
    write(&root, "README.md", "x\n");
    let docs = scan(&root);
    assert!(components(&docs.cdx).iter().all(|c| scope_of(c).is_none()));
    assert_eq!(doc_field_all_formats(&docs, C226), None);
}

/// FR-012: `--include-test-binaries` reports what #1524 skips, scoped, in a
/// tree that is not recognised.
#[test]
fn include_test_binaries_reports_them_test_scoped() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("src");
    elf(&root, "llvm/test/Inputs/core-file");
    elf(&root, "build/bin/product");
    let docs = scan_with("--path", &root, &["--include-test-binaries"]);
    assert_eq!(scope_of(named(&docs.cdx, "core-file")).as_deref(), Some("test-directory"));
    assert_eq!(scope_of(named(&docs.cdx, "product")), None);
    let cov = doc_field_all_formats(&docs, C226).unwrap();
    assert_eq!(cov["installed-tree"], "not-recognised");
    assert_eq!(cov["scoped"]["test-directory"], 1);
}

/// FR-015 (clarified) and FR-013: an extracted rootfs with a dpkg database
/// is an installed tree; a dpkg-owned file under `tests/` is not scoped.
#[test]
fn an_extracted_rootfs_with_an_os_database_is_recognised() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("rootfs");
    write(&root, "etc/os-release", "ID=debian\nVERSION_ID=\"12\"\n");
    dpkg_owning(&root, "waybill-fixture-s", &["usr/share/waybill-fixture-s/tests/owned"]);
    script(&root, "usr/share/waybill-fixture-s/tests/owned");
    script(&root, "usr/share/waybill-fixture-s/tests/free");
    // `full`, so the owned file has a file-tier component to (not) scope.
    let docs = scan_with("--path", &root, &["--file-inventory", "full"]);
    assert_eq!(scope_of(named(&docs.cdx, "free")).as_deref(), Some("test-directory"));
    assert_eq!(scope_of(named(&docs.cdx, "owned")), None);
    assert_eq!(doc_field_all_formats(&docs, C226).unwrap()["installed-tree"], "recognised");
}

/// FR-013: a CTest file an OS package owns declares nothing.
#[test]
fn an_os_owned_declaration_is_skipped_and_counted() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("rootfs");
    write(&root, "etc/os-release", "ID=debian\nVERSION_ID=\"12\"\n");
    let ctest = "usr/lib/waybill-fixture-t/CTestTestfile.cmake";
    dpkg_owning(&root, "waybill-fixture-t", &[ctest]);
    write(&root, ctest, "add_test(t \"./t-exe\")\n");
    elf(&root, "usr/lib/waybill-fixture-t/t-exe");
    let docs: Docs = scan(&root);
    assert_eq!(scope_of(named(&docs.cdx, "t-exe")), None);
    let cov = doc_field_all_formats(&docs, C226).unwrap();
    assert_eq!(cov["declarations"]["owned-by-os-package"], 1);
    assert_eq!(cov["declarations"]["ctest"], 0);
}

/// FR-007: the scope never flows to what a test package depends on. The
/// test package here is a `.pc` component whose `Requires` names the
/// product, so a real dependency edge exists for propagation to travel.
#[test]
fn a_product_a_test_package_requires_stays_unscoped() {
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path().join("sdk");
    let sdk = "opt/sdk";
    write(&root, &format!("{sdk}/lib/pkgconfig/waybill-fixture-q.pc"), "Version: 2.0\n");
    write(&root, &format!("{sdk}/lib/pkgconfig/waybill-fixture-q-tests.pc"), "Version: 2.0\nRequires: waybill-fixture-q\n");
    elf(&root, &format!("{sdk}/libexec/waybill-fixture-q/q-unit"));
    let dir = format!("{sdk}/lib/cmake/waybill-fixture-q-tests");
    write(&root, &format!("{dir}/waybill-fixture-q-tests-targets.cmake"), &main_file(3));
    write(
        &root,
        &format!("{dir}/waybill-fixture-q-tests-targets-release.cmake"),
        "set_target_properties(wf::q PROPERTIES\n  IMPORTED_LOCATION_RELEASE \"${_IMPORT_PREFIX}/libexec/waybill-fixture-q/q-unit\"\n  )\n",
    );
    let docs = scan(&root);
    let tests_pkg = component(&docs.cdx, "pkg:generic/waybill-fixture-q-tests@2.0").unwrap();
    assert_eq!(scope_of(tests_pkg).as_deref(), Some("exported-targets-test-package"));
    assert_eq!(scope_of(named(&docs.cdx, "q-unit")).as_deref(), Some("exported-targets-test-package"));
    // The edge exists, and the product it reaches is not scoped.
    assert_eq!(common::installed_lib::depends_on(&docs.cdx, "pkg:generic/waybill-fixture-q-tests@2.0"), ["pkg:generic/waybill-fixture-q@2.0"]);
    assert_eq!(scope_of(component(&docs.cdx, "pkg:generic/waybill-fixture-q@2.0").unwrap()), None);
}
