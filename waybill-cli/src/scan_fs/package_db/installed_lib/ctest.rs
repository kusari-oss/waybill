//! Installed `CTestTestfile.cmake` files: test declarations (spec 1533,
//! research R1).
//!
//! A project that installs its tests often installs the CTest file that
//! runs them, written "for install time" with paths relative to the file:
//! `add_test(rocblas-test_quick "../rocblas-test" --gtest_filter=…)`. Each
//! `add_test` names the executable (or, behind an interpreter, the script)
//! that is the test. Read textually; nothing is evaluated, and `include()`
//! and `subdirs()` are not followed: the walker finds every CTest file, and
//! an included discovery script names nothing without running CMake.

use super::cmake_version::{commands, strip_comments};

/// Interpreters whose script argument, not the interpreter, is the test.
const INTERPRETERS: [&str; 6] = ["python", "python3", "bash", "sh", "perl", "env"];

/// `add_test(NAME … COMMAND …)` keywords that end the command.
const KEYWORDS: [&str; 4] = ["CONFIGURATIONS", "WORKING_DIRECTORY", "COMMAND_EXPAND_LISTS", "NAME"];

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub(crate) struct Parsed {
    /// Each `add_test`'s command words, in file order.
    pub(crate) tests: Vec<Vec<String>>,
    /// `include()` lines, counted as unresolved declarations.
    pub(crate) includes: usize,
}

/// What one `add_test` command names, before resolution against the root.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Named {
    /// A path relative to the CTest file's directory.
    Direct(String),
    /// Behind an interpreter: the arguments that may be the script, of which
    /// only those that resolve to a shipped file count.
    Interpreter(Vec<String>),
    /// A variable, generator expression, absolute path, bare program name,
    /// or no command at all.
    Unresolved,
}

pub(crate) fn parse(content: &str) -> Parsed {
    let text = strip_comments(content);
    let mut out = Parsed::default();
    for (command, args) in commands(&text) {
        let words: Vec<String> = args.into_iter().map(|a| a.text).collect();
        match command.to_ascii_lowercase().as_str() {
            "add_test" => out.tests.push(test_command(&words)),
            "include" => out.includes += 1,
            _ => {}
        }
    }
    out
}

/// The command of an `add_test`, in either signature.
fn test_command(args: &[String]) -> Vec<String> {
    if args.first().map(String::as_str) == Some("NAME") {
        let Some(at) = args.iter().position(|a| a == "COMMAND") else {
            return Vec::new();
        };
        return args[at + 1..].iter().take_while(|a| !KEYWORDS.contains(&a.as_str())).cloned().collect();
    }
    args.iter().skip(1).cloned().collect()
}

/// Classify one test command (research R1).
pub(crate) fn named(command: &[String]) -> Named {
    let Some(word) = command.first() else {
        return Named::Unresolved;
    };
    let base = word.rsplit('/').next().unwrap_or(word);
    if INTERPRETERS.contains(&base) {
        let scripts: Vec<String> = command[1..]
            .iter()
            .filter(|a| !a.starts_with('-') && !a.contains('=') && plain_relative(a))
            .cloned()
            .collect();
        return if scripts.is_empty() { Named::Unresolved } else { Named::Interpreter(scripts) };
    }
    if plain_relative(word) && word.contains('/') {
        Named::Direct(word.clone())
    } else {
        Named::Unresolved
    }
}

/// No variable, no generator expression, not absolute.
fn plain_relative(word: &str) -> bool {
    !word.is_empty() && !word.contains("${") && !word.contains("$<") && !word.starts_with('/')
}

#[cfg(test)]
#[cfg_attr(test, allow(clippy::unwrap_used))]
mod tests {
    use super::*;

    fn s(v: &[&str]) -> Vec<String> {
        v.iter().map(|x| x.to_string()).collect()
    }

    /// The install-time form the ROCm SDK's CTest files use (research R1).
    #[test]
    fn the_install_time_form() {
        let p = parse(
            "# generated by waybill-fixture-p for install time\n\
             add_test(waybill-fixture-p-test_quick \"../waybill-fixture-p-test\" --gtest_filter=*quick*)\n\
             set_tests_properties(waybill-fixture-p-test_quick PROPERTIES LABELS \"quick\" TIMEOUT 600)\n\
             add_test(\"case one smoke\" \"../../case-one\" --emulation smoke)\n",
        );
        assert_eq!(p.tests.len(), 2);
        assert_eq!(named(&p.tests[0]), Named::Direct("../waybill-fixture-p-test".into()));
        assert_eq!(named(&p.tests[1]), Named::Direct("../../case-one".into()));
    }

    #[test]
    fn the_keyword_form_and_a_bracket_name() {
        let p = parse("add_test(NAME [=[a b]=] COMMAND ../t1 --x WORKING_DIRECTORY /w)\nadd_test([=[c d]=] \"../t2\")\n");
        assert_eq!(p.tests, vec![s(&["../t1", "--x"]), s(&["../t2"])]);
        assert_eq!(parse("add_test(NAME x)\n").tests, vec![Vec::<String>::new()]);
    }

    /// The interpreter is never the test; its script is.
    #[test]
    fn an_interpreter_names_its_script() {
        let p = parse("add_test([=[t]=] \"python3\" \"-m\" \"pytest\" \"--junitxml=tests/t.xml\" \"tests/test_t.py\")\n");
        assert_eq!(named(&p.tests[0]), Named::Interpreter(s(&["pytest", "tests/test_t.py"])));
        assert_eq!(named(&s(&["/usr/bin/bash", "run.sh"])), Named::Interpreter(s(&["run.sh"])));
        assert_eq!(named(&s(&["env", "A=1", "../t"])), Named::Interpreter(s(&["../t"])));
        assert_eq!(named(&s(&["sh", "-c", "${X}"])), Named::Unresolved);
    }

    #[test]
    fn what_is_never_resolved() {
        for cmd in [
            s(&["${_EXE}", "${_ARGS}"]),
            s(&["$<TARGET_FILE:t>"]),
            s(&["/home/runner/build/t"]),
            s(&["t"]),
            s(&[]),
        ] {
            assert_eq!(named(&cmd), Named::Unresolved, "{cmd:?}");
        }
    }

    /// `include()` is counted and not followed; `subdirs()` is ignored.
    #[test]
    fn includes_and_subdirs() {
        let p = parse("subdirs(catch_tests)\ninclude(script/A_include.cmake)\ninclude(script/B_include.cmake)\n");
        assert_eq!(p.includes, 2);
        assert!(p.tests.is_empty());
    }

    #[test]
    fn comments_and_truncation() {
        let p = parse("# add_test(x \"../commented\")\nadd_test(y \"../real\")\nadd_test(z \"../trunc");
        assert_eq!(p.tests[0], s(&["../real"]));
        assert!(p.tests.iter().all(|t| t.first().map(String::as_str) != Some("../commented")));
    }
}
