//! Parser for Yarn's `yarn.lock` file (milestone 106 US5, closes #274).
//!
//! Yarn has two distinct lockfile formats:
//!
//! 1. **v1 (Yarn Classic)** — text-based, indent-2 + indent-4 structure.
//!    Header: `# yarn lockfile v1`. Top-level entries are `"<descriptor>":`
//!    lines with descriptor strings like `"foo@^1.0.0"` (or comma-joined
//!    aliases like `"foo@^1.0.0", "foo@^1.1.0":`). Each entry's body
//!    declares `version "..."`, optional `resolved "..."`, optional
//!    `integrity ...`, and an optional `dependencies:` sub-block.
//!
//! 2. **Berry (Yarn 2+)** — YAML-shaped (parses with `serde_yaml`).
//!    Header: `# This file is generated by running "yarn install"`. Has a
//!    `__metadata:` block at the top. Descriptors carry an `npm:`
//!    protocol prefix (`"foo@npm:^1.0.0"`). Per-entry block uses YAML
//!    mappings (`version:`, `resolution:`, `dependencies:`, ...).
//!
//! Format detection is content-sniffed (we look for `__metadata:` at a
//! line start; presence ⇒ Berry, absence ⇒ v1). Both formats emit
//! `pkg:npm/<name>@<version>` PURLs (scoped names URL-encode the `@`
//! per PURL spec).
//!
//! Dependency edges from each entry's `dependencies:` map populate
//! `PackageDbEntry.depends`. The scan orchestrator looks each name up
//! against the in-scan entry set and drops unresolved ones — same
//! pattern as npm `package-lock.json`.

use std::collections::BTreeMap;
use std::path::Path;

use super::super::PackageDbEntry;
use super::build_npm_purl;

pub(super) fn read_yarn_lock(
    rootfs: &Path,
    _include_dev: bool,
    // Milestone 1271 T022 (FR-011): member discovery expands the root
    // manifest's `workspaces` patterns, which accept `**`, so it walks
    // the tree. The operator's `--exclude-path` set reached only
    // `mod.rs` before this; it has to reach the walk itself.
    exclude_set: &super::super::exclude_path::ExclusionSet,
) -> Option<Vec<PackageDbEntry>> {
    let path = rootfs.join("yarn.lock");
    let text = std::fs::read_to_string(&path).ok()?;
    let source_path = path.to_string_lossy().into_owned();
    // Milestone 181 T003 — also read root package.json for the m181
    // optional-dep classifier (v1's `optionalDependencies:` sub-block
    // guard, Berry's `dependenciesMeta.<name>.optional` cross-reference,
    // and the m180 peer-precedence guard). Value::Null on any error
    // per FR-004 fail-safe: parsers safely yield zero optional entries
    // when the file is missing/unparseable.
    let pkg_json_path = rootfs.join("package.json");
    let pkg_json = std::fs::read_to_string(&pkg_json_path)
        .ok()
        .and_then(|s| serde_json::from_str::<serde_json::Value>(&s).ok())
        .unwrap_or(serde_json::Value::Null);
    if pkg_json.is_null() {
        tracing::debug!(
            path = %pkg_json_path.display(),
            "package.json missing or unparseable — yarn optional-dep classification skipped (FR-004 fail-safe)"
        );
    }
    let mut out = parse_yarn_lock(&text, &source_path, &pkg_json);
    // Milestone 1271 US2 (issue #1297) — assign development scope from
    // the workspace manifests. Neither yarn dialect records the axis;
    // see `apply_yarn_dev_scope`.
    apply_yarn_dev_scope(&mut out, rootfs, &text, &pkg_json, exclude_set);
    if out.is_empty() {
        None
    } else {
        Some(out)
    }
}

/// Parse a yarn.lock document (auto-detects v1 vs Berry).
///
/// Milestone 181 T003: `pkg_json` is the parsed root `package.json`
/// (`serde_json::Value::Null` if missing/unparseable). Both parsers
/// use it for optional-dep classification per m181 spec.md FR-001..
/// FR-005. Existing test callers pre-m181 pass `&Value::Null` for
/// backward-compat (they don't exercise the classification path).
pub(super) fn parse_yarn_lock(
    text: &str,
    source_path: &str,
    pkg_json: &serde_json::Value,
) -> Vec<PackageDbEntry> {
    if is_berry(text) {
        parse_berry(text, source_path, pkg_json)
    } else {
        parse_v1(text, source_path, pkg_json)
    }
}

fn is_berry(text: &str) -> bool {
    text.lines()
        .take(50)
        .any(|line| line.trim_start().starts_with("__metadata:"))
}

// ────────────────────────────────────────────────────────────────────
// Berry parser (Yarn 2+)
// ────────────────────────────────────────────────────────────────────

fn parse_berry(
    text: &str,
    source_path: &str,
    pkg_json: &serde_json::Value,
) -> Vec<PackageDbEntry> {
    // Skip the `__metadata:` block by stripping it from a deserialized
    // map. yarn.lock Berry is YAML-shaped — serde_yaml accepts it.
    let parsed: serde_yaml::Value = match serde_yaml::from_str(text) {
        Ok(v) => v,
        Err(e) => {
            tracing::warn!(
                path = %source_path,
                error = %e,
                "failed to parse Berry-format yarn.lock (skipping; FR-015)"
            );
            return Vec::new();
        }
    };
    let Some(mapping) = parsed.as_mapping() else {
        return Vec::new();
    };

    // Milestone 181 T012 — build the Berry optional-name set from
    // `package.json > dependenciesMeta.<name>.optional = true` (m181
    // FR-003). Berry's lockfile does NOT carry the flag (it lives in
    // package.json only). Apply the peer-precedence guard immediately
    // per m181 FR-005: names that ALSO satisfy m180's
    // `is_peer_optional` predicate are removed from the set so m178's
    // `PROVIDED_DEPENDENCY_OF` classification wins (KEEP-BOTH polarity).
    let mut optional_names: std::collections::HashSet<String> =
        berry_optional_names_from_pkg_json(pkg_json);
    optional_names.retain(|n| {
        !super::peer_optional::is_peer_optional(n, pkg_json)
    });

    let mut out = Vec::new();
    for (raw_key, entry) in mapping {
        let Some(key_str) = raw_key.as_str() else {
            continue;
        };
        if key_str == "__metadata" {
            continue;
        }
        let Some(body) = entry.as_mapping() else {
            continue;
        };
        // Use the first descriptor in the (possibly comma-joined) key
        // to get the package name. Both `"foo@npm:^1.0.0"` and
        // `"foo@npm:^1.0.0, foo@npm:^2.0.0"` start with the name.
        let name = match descriptor_to_name(key_str) {
            Some(n) => n,
            None => continue,
        };
        let version = body
            .get(serde_yaml::Value::String("version".into()))
            .and_then(|v| v.as_str())
            .unwrap_or("")
            .trim()
            .to_string();
        if version.is_empty() {
            continue;
        }
        let dep_names = body
            .get(serde_yaml::Value::String("dependencies".into()))
            .and_then(|v| v.as_mapping())
            .map(|m| {
                m.keys()
                    .filter_map(|k| k.as_str().map(str::to_string))
                    .collect::<Vec<_>>()
            })
            .unwrap_or_default();
        if let Some(entry) = build_entry(&name, &version, source_path, dep_names, &optional_names) {
            out.push(entry);
        }
    }
    out
}

/// Milestone 181 T012 — extract the set of names declared as optional
/// via `package.json > dependenciesMeta.<name>.optional = true`. Berry
/// stores optional-dep information out-of-band from the lockfile — the
/// package.json map is the ONLY source. Any error (missing field,
/// wrong shape, non-object meta) safely collapses to the empty set via
/// the option-chain per m181 spec.md Assumption 2.
fn berry_optional_names_from_pkg_json(
    pkg_json: &serde_json::Value,
) -> std::collections::HashSet<String> {
    pkg_json
        .get("dependenciesMeta")
        .and_then(|v| v.as_object())
        .into_iter()
        .flat_map(|obj| obj.iter())
        .filter(|(_, meta)| meta.get("optional").and_then(|v| v.as_bool()) == Some(true))
        .map(|(name, _)| name.to_string())
        .collect()
}

// ────────────────────────────────────────────────────────────────────
// v1 parser (Yarn Classic, line-oriented text format)
// ────────────────────────────────────────────────────────────────────
//
// Top-level entry shape:
//
//   "foo@^1.0.0", "foo@^1.1.0":
//     version "1.0.5"
//     resolved "https://..."
//     integrity sha512-...
//     dependencies:
//       bar "^2.0.0"

fn parse_v1(
    text: &str,
    source_path: &str,
    pkg_json: &serde_json::Value,
) -> Vec<PackageDbEntry> {
    // Two-pass aggregator keyed by (name, version) so multi-alias
    // headers (where one block declares two aliases of the same coord)
    // don't double-emit.
    let mut acc: BTreeMap<(String, String), Vec<String>> = BTreeMap::new();

    // Milestone 159 (issue #493): collect all detected yarn v1
    // aliases during the parse pass. Consumed post-loop to build the
    // alias_map (edge rewriting) + reverse-map (annotation emission).
    let mut aliases: Vec<super::alias_mapping::AliasResolution> = Vec::new();
    // Per-canonical local-name list for FR-006 annotation attachment.
    // Key = `<aliased_name>@<aliased_version>` canonical string; value
    // = deduped-preserved-order Vec<local_name>.
    let mut annotation_locals: BTreeMap<String, Vec<String>> = BTreeMap::new();

    // Milestone 181 T004 — scan-wide accumulators for the optional-
    // dep classifier (spec.md FR-001 + FR-007). `optional_children_seen`
    // collects every child name that appeared under some parent's
    // `optionalDependencies:` sub-block; `regular_children_seen`
    // collects every child from regular `dependencies:` sub-blocks.
    // The final classifier input (below) is the set-difference
    // `optional - regular` — enforces FR-007's diamond-shape rule that
    // Runtime (regular) wins over Optional when a name appears in both.
    let mut optional_children_seen: std::collections::HashSet<String> =
        Default::default();
    let mut regular_children_seen: std::collections::HashSet<String> =
        Default::default();

    let mut lines = text.lines().peekable();
    while let Some(line) = lines.next() {
        if !is_v1_entry_header(line) {
            continue;
        }
        let header_name = match v1_header_to_name(line) {
            Some(n) => n,
            None => continue,
        };
        // Collect the indented body for this entry until the next
        // unindented line (a comment or another header).
        let mut version: Option<String> = None;
        let mut in_deps_block = false;
        // Milestone 181 T004 — companion boolean flipped when the
        // current sub-block is `optionalDependencies:` (vs the
        // pre-m181 flat `dependencies:` OR `optionalDependencies:`
        // fallthrough). Routes each collected child name to the
        // per-entry `optional_dep_names` accumulator when true.
        let mut is_optional_block = false;
        let mut dep_names: Vec<String> = Vec::new();
        let mut optional_dep_names: Vec<String> = Vec::new();
        while let Some(&body_line) = lines.peek() {
            let leading_ws = body_line.len() - body_line.trim_start().len();
            if !body_line.trim().is_empty() && leading_ws == 0 {
                break;
            }
            lines.next();
            let trimmed = body_line.trim();
            if trimmed.is_empty() {
                in_deps_block = false;
                is_optional_block = false;
                continue;
            }
            if leading_ws == 2 {
                in_deps_block = false;
                is_optional_block = false;
                if let Some(rest) = trimmed.strip_prefix("version ") {
                    version = Some(unquote(rest.trim()).to_string());
                } else if trimmed == "dependencies:" {
                    in_deps_block = true;
                    is_optional_block = false;
                } else if trimmed == "optionalDependencies:" {
                    in_deps_block = true;
                    is_optional_block = true;
                }
            } else if leading_ws >= 4 && in_deps_block {
                // "name version-range" line; first token is the dep name.
                if let Some((dep_name, _rest)) = trimmed.split_once(char::is_whitespace) {
                    let dep_clean = unquote(dep_name.trim()).to_string();
                    if !dep_clean.is_empty() {
                        if is_optional_block {
                            optional_dep_names.push(dep_clean);
                        } else {
                            dep_names.push(dep_clean);
                        }
                    }
                }
            }
        }
        if let Some(v) = version {
            if !v.is_empty() {
                // Milestone 181 T004 — record every child name into the
                // scan-wide sets BEFORE the m159 alias merge. Diamond-
                // shape rule (FR-007) is enforced post-loop by
                // set-difference.
                for n in &optional_dep_names {
                    optional_children_seen.insert(n.clone());
                }
                for n in &dep_names {
                    regular_children_seen.insert(n.clone());
                }
                // Merge the two per-entry accumulators into `dep_names`
                // for downstream edge emission (edges don't care about
                // the regular/optional distinction — same as pre-m181).
                dep_names.extend(optional_dep_names);
                // Milestone 159 — check for yarn v1 key-side alias. When
                // detected, the entry is aggregated under the ALIASED
                // canonical identity per FR-003, and the local-name is
                // recorded for FR-006 annotation attachment.
                let (name, canonical_version) =
                    if let Some(alias) = super::alias_mapping::detect_yarn_v1_alias(
                        line,
                        &v,
                        source_path,
                    ) {
                        let canonical =
                            format!("{}@{}", alias.aliased_name, alias.aliased_version);
                        let locals = annotation_locals.entry(canonical).or_default();
                        if !locals.contains(&alias.local_name) {
                            locals.push(alias.local_name.clone());
                        }
                        let aliased_name = alias.aliased_name.clone();
                        let aliased_version = alias.aliased_version.clone();
                        aliases.push(alias);
                        (aliased_name, aliased_version)
                    } else {
                        (header_name.clone(), v)
                    };
                acc.entry((name, canonical_version))
                    .or_default()
                    .extend(dep_names);
            }
        }
    }

    // Milestone 159 post-processing: build alias_map for edge
    // rewriting on OTHER entries' deps that reference the local-name.
    let mut alias_map: super::alias_mapping::AliasMap = std::collections::HashMap::new();
    for a in &aliases {
        alias_map.entry(a.local_name.clone()).or_insert_with(|| {
            super::alias_mapping::AliasedIdentity {
                aliased_name: a.aliased_name.clone(),
                aliased_version: a.aliased_version.clone(),
            }
        });
    }
    let alias_count = aliases.len();

    // Milestone 181 T004 — compute the final optional-name set:
    // `optional_children_seen - regular_children_seen` enforces the
    // FR-007 diamond-shape rule (Runtime wins when a name appears in
    // both sub-block kinds across any parents). Then apply the m180
    // peer-precedence guard per FR-005: names that are ALSO peer-
    // optional per the root package.json get removed so m178's
    // `PROVIDED_DEPENDENCY_OF` classification wins (KEEP-BOTH
    // polarity).
    let mut optional_names: std::collections::HashSet<String> = optional_children_seen
        .difference(&regular_children_seen)
        .cloned()
        .collect();
    optional_names.retain(|n| {
        !super::peer_optional::is_peer_optional(n, pkg_json)
    });

    let mut out = Vec::new();
    for ((name, version), deps) in acc {
        // De-duplicate dep names while preserving first-seen order.
        let mut seen: std::collections::BTreeSet<String> = Default::default();
        let mut unique: Vec<String> = deps
            .into_iter()
            .filter(|d| seen.insert(d.clone()))
            .collect();
        // Milestone 159 FR-005 — rewrite any local-name refs in this
        // entry's deps to the aliased canonical name so the graph is
        // connected via the resolved identity.
        if alias_count > 0 {
            unique = super::alias_mapping::rewrite_dep_names(&unique, &alias_map);
        }
        if let Some(mut entry) = build_entry(&name, &version, source_path, unique, &optional_names) {
            // Milestone 159 FR-006 — attach `waybill:yarn-alias`
            // annotation on aliased components. Single local-name
            // emits Value::String; multi-alias (FR-012) emits
            // Value::Array with sorted local-names.
            let canonical = format!("{}@{}", name, version);
            if let Some(locals) = annotation_locals.get(&canonical) {
                let mut sorted = locals.clone();
                sorted.sort();
                let value = if sorted.len() == 1 {
                    serde_json::Value::String(sorted[0].clone())
                } else {
                    serde_json::Value::Array(
                        sorted
                            .into_iter()
                            .map(serde_json::Value::String)
                            .collect(),
                    )
                };
                entry
                    .extra_annotations
                    .insert("waybill:yarn-alias".to_string(), value);
            }
            out.push(entry);
        }
    }

    // Milestone 159 FR-011 info log — emit ONLY when at least one
    // alias was resolved.
    if alias_count > 0 {
        tracing::info!(
            lockfile_path = %source_path,
            alias_count = alias_count,
            alias_ecosystem = "yarn",
            "npm-alias resolution completed"
        );
    }

    out
}

fn is_v1_entry_header(line: &str) -> bool {
    // Top-level headers start at column 0, are non-comment, and end
    // with `:`. Examples:
    //   "foo@^1.0.0":
    //   foo@^1.0.0:
    //   "foo@^1.0.0", "foo@^1.1.0":
    if line.is_empty() {
        return false;
    }
    if line.starts_with(' ') || line.starts_with('\t') {
        return false;
    }
    if line.starts_with('#') {
        return false;
    }
    line.trim_end().ends_with(':')
}

fn v1_header_to_name(line: &str) -> Option<String> {
    let trimmed = line.trim_end_matches(':');
    // Split on `,` to get alias list; take the first descriptor.
    let first = trimmed.split(',').next()?.trim();
    descriptor_to_name(first)
}

/// Turn a descriptor like `foo@^1.0.0`, `"foo@^1.0.0"`, `"@types/node@^20.0.0"`,
/// or `"@types/node@npm:^20.0.0"` into the bare package name (`foo`,
/// `@types/node`, etc.).
fn descriptor_to_name(descriptor: &str) -> Option<String> {
    let unquoted = unquote(descriptor.trim());
    if unquoted.is_empty() {
        return None;
    }
    // Scoped names start with `@scope/name@...`. Strip the leading `@`
    // before searching for the descriptor's `@<version>` separator.
    let (search_target, scoped_prefix) = if let Some(rest) = unquoted.strip_prefix('@') {
        (rest, true)
    } else {
        (unquoted.as_ref(), false)
    };
    let at_idx = search_target.rfind('@')?;
    let name_part = &search_target[..at_idx];
    if name_part.is_empty() {
        return None;
    }
    Some(if scoped_prefix {
        format!("@{name_part}")
    } else {
        name_part.to_string()
    })
}

fn unquote(s: &str) -> String {
    let trimmed = s.trim();
    if trimmed.len() >= 2 && trimmed.starts_with('"') && trimmed.ends_with('"') {
        trimmed[1..trimmed.len() - 1].to_string()
    } else {
        trimmed.to_string()
    }
}

